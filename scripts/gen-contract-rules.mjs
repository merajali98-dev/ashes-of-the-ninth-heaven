// Writes contracts/items/src/rules_gen.rs from js/market/merchant-rules.js, so the contract enforces exactly the
// parameters of the one pricing file. Run: node scripts/gen-contract-rules.mjs   (a test fails if the output is stale)
import {writeFile} from 'node:fs/promises';
import * as R from '../js/market/merchant-rules.js';

const str = s => JSON.stringify(String(s));
const int = n => { if (!Number.isSafeInteger(n)) throw new Error('not an integer: ' + n); return String(n); };

export function renderRules() {
  const t = id => R.temperamentOf(R.MERCHANTS.find(m => m.id === id));
  const lines = [
    '// @generated by scripts/gen-contract-rules.mjs from js/market/merchant-rules.js. Do not edit by hand.',
    '// Every parameter the contract uses to price merchant trades comes from that one readable file.',
    'use crate::pricing::{EventDef, MerchantDef, Role, Temperament};',
    '',
    `pub const CENTS: i128 = ${int(R.CENTS)};`,
    `pub const BPS: i128 = ${int(R.BPS)};`,
    `pub const PRICE_FLOOR_BPS: i128 = ${int(R.PRICE_BAND.floorBps)};`,
    `pub const PRICE_CEILING_BPS: i128 = ${int(R.PRICE_BAND.ceilingBps)};`,
    `pub const TICKS_PER_DAY: u64 = ${int(R.TIME.ticksPerDay)};`,
    `pub const TICKS_PER_WEEK: u64 = ${int(R.TIME.ticksPerWeek)};`,
    `pub const MAX_CATCH_UP_TICKS: u64 = ${int(R.TIME.maxCatchUpTicks)};`,
    `pub const DEMAND_MIN_BPS: i128 = ${int(R.DEMAND_BAND.minBps)};`,
    `pub const DEMAND_MAX_BPS: i128 = ${int(R.DEMAND_BAND.maxBps)};`,
    `pub const STOREROOM_BPS: i128 = ${int(R.STOREROOM_BPS)};`,
    `pub const SPECIALTY_PREMIUM_BPS: i128 = ${int(R.SPECIALTY_PREMIUM_BPS)};`,
    `pub const PURSE_THIN_BELOW_BPS: i128 = ${int(R.PURSE.thinBelowBps)};`,
    `pub const PURSE_THIN_PAY_BPS: i128 = ${int(R.PURSE.thinPayBps)};`,
    `pub const PURSE_STOP_BUYING_BELOW_BPS: i128 = ${int(R.PURSE.stopBuyingBelowBps)};`,
    `pub const PURSE_CLOSE_AT_DAY_END_BELOW_BPS: i128 = ${int(R.PURSE.closeAtDayEndBelowBps)};`,
    `pub const PURSE_CLOSE_BELOW_BPS: i128 = ${int(R.PURSE.closeBelowBps)};`,
    `pub const PURSE_REOPEN_AT_BPS: i128 = ${int(R.PURSE.reopenAtBps)};`,
    `pub const PURSE_UPKEEP_BPS: i128 = ${int(R.PURSE.upkeepBps)};`,
    `pub const CARAVAN_RESTOCK_COST_BPS: i128 = ${int(R.CARAVAN.restockCostBps)};`,
    `pub const CARAVAN_SURPLUS_VALUE_BPS: i128 = ${int(R.CARAVAN.surplusValueBps)};`,
    `pub const ADAPT_EVERY_TICKS: u64 = ${int(R.ADAPTATION.everyTicks)};`,
    `pub const ADAPT_BAND_BPS: i128 = ${int(R.ADAPTATION.bandBps)};`,
    `pub const ADAPT_STEP_BPS: i128 = ${int(R.ADAPTATION.stepBps)};`,
    `pub const ADAPT_MIN_BPS: i128 = ${int(R.ADAPTATION.minBps)};`,
    `pub const ADAPT_MAX_BPS: i128 = ${int(R.ADAPTATION.maxBps)};`,
    `pub const TARGETS_SPECIALTY: [i128; 5] = [${R.TARGETS.specialty.map(int).join(', ')}];`,
    `pub const TARGETS_SIDE: [i128; 5] = [${R.TARGETS.side.map(int).join(', ')}];`,
    `pub const TARGET_CONSUMABLE: i128 = ${int(R.TARGETS.consumable)};`,
    `pub const EDICT_BOOST_BPS: i128 = ${int(R.EDICT.boostBps)};`,
    `pub const EDICT_SCHOOLS: [&str; ${R.EDICT.schools.length}] = [${R.EDICT.schools.map(str).join(', ')}];`,
    `pub const EVENT_PERIOD_TICKS: u64 = ${int(R.EVENTS.periodTicks)};`,
    `pub const EVENT_DURATION_TICKS: u64 = ${int(R.EVENTS.durationTicks)};`,
    `pub const EVENTS: [EventDef; ${R.EVENTS.list.length}] = [`,
    ...R.EVENTS.list.map(e => `    EventDef { id: ${str(e.id)}, family: ${str(e.family)}, price_bps: ${int(e.priceBps)} },`),
    '];',
    `pub const TAX_BASE_BPS: i128 = ${int(R.TAX.baseBps)};`,
    `pub const PATRON_MAX_PUBLIC_BPS: i128 = ${int(R.PATRONAGE.maxPublicBps)};`,
    `pub const PATRON_MAX_PATRONS: usize = ${int(R.PATRONAGE.maxPatrons)};`,
    `pub const MERCHANTS: [MerchantDef; ${R.MERCHANTS.length}] = [`,
    ...R.MERCHANTS.map(m => {
      const x = t(m.id);
      return `    MerchantDef { id: ${str(m.id)}, name: ${str(m.name)}, start_cash: ${int(m.startCash)}, consumables: ${Boolean(m.consumables)},\n` +
        `        temperament: Temperament { k_quarters: ${int(x.kQuarters)}, spread_bps: ${int(x.spreadBps)}, flow_weight_bps: ${int(x.flowWeightBps)}, flow_fade_bps: ${int(x.flowFadeBps)}, reversion_bps: ${int(x.reversionBps)}, loyalty_bps: ${int(x.loyaltyBps)} },\n` +
        `        families: &[${Object.entries(m.families).map(([f, role]) => `(${str(f)}, Role::${role === 'specialty' ? 'Specialty' : 'Side'})`).join(', ')}] },`;
    }),
    '];',
    '',
  ];
  return lines.join('\n');
}

if (process.argv[1]?.endsWith('gen-contract-rules.mjs')) {
  await writeFile(new URL('../contracts/items/src/rules_gen.rs', import.meta.url), renderRules());
  console.log('Wrote contracts/items/src/rules_gen.rs');
}
